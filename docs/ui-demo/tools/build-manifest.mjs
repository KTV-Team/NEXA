/**
 * NEXA UI demo — write the gallery manifest.
 *
 * Reads tools/pages.mjs and emits assets/screens.js, which index.html consumes
 * to build the gallery. Run after tools/cdp-check.mjs so the referenced
 * thumbnails exist in .shots/.
 *
 * Run:  node docs/ui-demo/tools/build-manifest.mjs
 */

import { writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { SCREENS } from './pages.mjs';

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(HERE, '..');
const OUT = resolve(ROOT, 'assets', 'screens.js');

const groups = [];
for (const screen of SCREENS) {
  let group = groups.find((g) => g.name === screen.group);
  if (!group) {
    group = { name: screen.group, screens: [] };
    groups.push(group);
  }
  group.screens.push({
    file: screen.file,
    title: screen.title,
    desc: screen.desc,
    surface: screen.surface,
    feature: screen.feature ?? null,
    w: screen.w,
    h: screen.h,
    shot: `.shots/${screen.file.replace(/\.html$/, '')}.png`,
    full: `.shots/${screen.file.replace(/\.html$/, '')}.full.png`,
  });
}

const body = `/* Generated by tools/build-manifest.mjs — do not edit by hand.
   ${SCREENS.length} screens across ${groups.length} groups. */

const SCREEN_GROUPS = ${JSON.stringify(groups, null, 2)};

const SCREEN_COUNT = ${SCREENS.length};
`;

writeFileSync(OUT, body, 'utf8');
console.log(`Wrote ${OUT} — ${SCREENS.length} screens in ${groups.length} groups.`);
